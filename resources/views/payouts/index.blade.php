    records: @js($payouts),
    searchQuery: '',
    statusFilter: 'All Statuses',
    programFilter: 'All Programs',
    barangayFilter: 'All Barangays',
    selectedRecord: null,
    detailsOpen: false,
    confirmationOpen: false,
    claimantType: 'self',
    selfIdVerified: false,
    representative: { name: '', relationship: '', contact: '' },
    proxyChecks: { seniorId: false, authorizationLetter: false, representativeId: false, proofOfLife: false },
    get filteredRecords() {
        return this.records.filter((record) => {
            const query = this.searchQuery.trim().toLowerCase();
            const matchesQuery = !query || record.id.toLowerCase().includes(query) || `${record.lastName} ${record.firstName}`.toLowerCase().includes(query);
            const matchesStatus = this.statusFilter === 'All Statuses' || record.status === this.statusFilter;
            const matchesProgram = this.programFilter === 'All Programs' || record.program === this.programFilter;
            const matchesBarangay = this.barangayFilter === 'All Barangays' || record.barangay === this.barangayFilter;
            return matchesQuery && matchesStatus && matchesProgram && matchesBarangay;
        });
    },
    get unclaimedCount() {
        return this.records.filter((record) => record.status === 'Unclaimed').length;
    },
    get claimedCount() {
        return this.records.filter((record) => record.status === 'Claimed').length;
    },
    get proxyCount() {
        return this.records.filter((record) => record.status === 'Claimed' && record.claim?.type === 'proxy').length;
    },
    get canRelease() {
        if (!this.selectedRecord || this.selectedRecord.status !== 'Unclaimed') {
            return false;
        }

        if (this.claimantType === 'self') {
            return this.selfIdVerified;
        }

        return !!this.representative.name && !!this.representative.relationship && !!this.representative.contact && this.proxyChecks.seniorId && this.proxyChecks.authorizationLetter && this.proxyChecks.representativeId && this.proxyChecks.proofOfLife;
    },
    formatAmount(value) {
        return `₱${Number(value).toLocaleString('en-PH')}`;
    },
    moneyText(value) {
        return this.formatAmount(value);
    },
    openDetails(id) {
        const found = this.records.find((record) => record.id === id);
        if (!found) return;

        this.selectedRecord = JSON.parse(JSON.stringify(found));
        this.detailsOpen = true;
        this.confirmationOpen = false;
        this.claimantType = this.selectedRecord.claim?.type === 'proxy' ? 'proxy' : 'self';
        this.selfIdVerified = false;
        this.representative = { name: '', relationship: '', contact: '' };
        this.proxyChecks = { seniorId: false, authorizationLetter: false, representativeId: false, proofOfLife: false };
    },
    closeDetails() {
        this.detailsOpen = false;
        this.confirmationOpen = false;
        this.selectedRecord = null;
    },
    openConfirmation() {
        if (!this.canRelease) return;
        this.confirmationOpen = true;
    },
    cancelConfirmation() {
        this.confirmationOpen = false;
    },
    confirmRelease() {
        if (!this.selectedRecord) return;

        const claimType = this.claimantType === 'proxy' ? 'proxy' : 'self';
        const claimDate = 'Oct 12, 2026';

        this.selectedRecord.status = 'Claimed';
        this.selectedRecord.claim = {
            type: claimType,
            name: claimType === 'proxy' ? this.representative.name : 'Self (Senior Citizen)',
            relationship: claimType === 'proxy' ? this.representative.relationship : '',
            contact: claimType === 'proxy' ? this.representative.contact : '',
            date: claimDate,
        };
        this.selectedRecord.releasedBy = 'Maria A. (OSCA Staff)';
        this.selectedRecord.releasedAt = 'Oct 12, 2026 at 10:30 AM';

        const index = this.records.findIndex((record) => record.id === this.selectedRecord.id);
        if (index >= 0) {
            this.records[index] = JSON.parse(JSON.stringify(this.selectedRecord));
        }

        this.confirmationOpen = false;
        this.detailsOpen = true;
    },
    get releaseTitle() {
        if (!this.selectedRecord) return 'Confirm & Release Payout';
        return `Confirm & Release Payout (${this.formatAmount(this.selectedRecord.amount)})`;
    },
    get summaryClaimText() {
        if (!this.selectedRecord) return '';
        if (this.selectedRecord.status === 'Claimed') {
            if (this.selectedRecord.claim?.type === 'proxy') {
                return `${this.selectedRecord.claim.name} (${this.selectedRecord.claim.relationship})`;
            }
            return 'Self (Senior Citizen in Person)';
        }
        return '';
    },
    get summaryDescriptor() {
        if (!this.selectedRecord) return '';
        return `${this.selectedRecord.barangay} · Age ${this.selectedRecord.age} · ${this.selectedRecord.program}`;
    },
    get claimDescription() {
        if (!this.selectedRecord) return '';
        if (this.selectedRecord.status === 'Claimed' && this.selectedRecord.claim?.type === 'proxy') {
            return `Claimed by Authorized Representative: ${this.selectedRecord.claim.name} (${this.selectedRecord.claim.relationship} · ${this.selectedRecord.claim.contact})`;
        }
        if (this.selectedRecord.status === 'Claimed') {
            return 'Claimed by: Self (Senior Citizen in Person)';
        }
        return '';
    }
